-- PaTiDungeon settings and status. Run via PaTiAdmin/tools/check.sh.
local wow = require("wow_api")

local function load()
    return wow.loadAddonFile("Logic.lua", {}).Logic
end

local never = function() return false end

describe("Logic.Migrate", function()
    it("creates defaults and keeps the 0.1.0 position and lock", function()
        local db = load().Migrate({ x = -330, y = 160, locked = true })
        assert.equal(-330, db.x)
        assert.equal(160, db.y)
        assert.is_true(db.locked)
        assert.is_false(db.collapsed)
        assert.equal(1, db.schema)
    end)

    it("keeps saved false values", function()
        local db = load().Migrate({ schema = 1, locked = false, collapsed = false, scale = 1.1 })
        assert.is_false(db.locked)
        assert.equal(1.1, db.scale)
    end)
end)

describe("Logic.RestoreDefaults", function()
    it("keeps the position", function()
        local db = load().RestoreDefaults({ x = 1, collapsed = true })
        assert.equal(1, db.x)
        assert.is_false(db.collapsed)
    end)
end)

describe("Logic.Status", function()
    it("normalises a dungeon", function()
        local status = load().Status({ inInstance = true, name = "Todesminen", instanceType = "party" }, never)
        assert.is_true(status.inInstance)
        assert.equal("Todesminen", status.name)
        assert.equal("TYPE_PARTY", status.typeKey)
    end)

    it("accepts 1/nil flags from older client APIs like 0.1.0 did", function()
        local status = load().Status({ inInstance = 1 }, never)
        assert.is_true(status.inInstance)
    end)

    it("keeps an unknown instance type as raw text without a key", function()
        local status = load().Status({ inInstance = true, instanceType = "delve" }, never)
        assert.is_nil(status.typeKey)
        assert.equal("delve", status.rawType)
    end)

    it("turns secret, empty or missing values into unknown", function()
        local secret = {}
        local isSecret = function(value) return rawequal(value, secret) end
        local status = load().Status({ inInstance = secret, name = "", instanceType = secret }, isSecret)
        assert.is_false(status.inInstance)
        assert.is_nil(status.name)
        assert.is_nil(status.typeKey)
    end)
end)

describe("Collapse state", function()
    it("a saved collapsed = true stays; Restore Defaults expands (documented) and keeps the position", function()
        local Logic = load()
        local db = Logic.Migrate({ x = 7, collapsed = true })
        assert.is_true(db.collapsed)
        Logic.RestoreDefaults(db)
        assert.is_false(db.collapsed)
        assert.equal(7, db.x)
    end)
end)

describe("Window settings (panel opacity)", function()
    it("old saves get 75 %; a saved value stays; Restore Defaults resets it; an old snapWindows is ignored", function()
        local M = load()
        local db = M.Migrate({ x = 12, y = 34 })
        assert.equal(0.75, db.opacity)
        assert.equal(12, db.x)
        db = M.Migrate({ opacity = 0.4, snapWindows = false })
        assert.equal(0.4, db.opacity)
        db = M.RestoreDefaults({ opacity = 0.4, snapWindows = false, bindings = {}, bindingRanks = {}, watch = {} })
        assert.equal(0.75, db.opacity)
    end)
end)

describe("Hand-drawn map (sketches)", function()
    it("keys a sketch by instance ID, else by name; nothing outside an instance", function()
        local M = load()
        assert.equal("id:3065", M.SketchKey({ inInstance = true, instanceID = 3065, name = "Die Halle der Thanen" }))
        assert.equal("name:Todesminen", M.SketchKey({ inInstance = true, instanceID = 0, name = "Todesminen" }))
        assert.is_nil(M.SketchKey({ inInstance = false, instanceID = 3065 }))
        assert.is_nil(M.SketchKey({ inInstance = true }))
    end)

    it("reads the instance ID, a secret one becomes unknown", function()
        local secret = {}
        local isSecret = function(value) return rawequal(value, secret) end
        local M = load()
        assert.equal(3065, M.Status({ inInstance = true, instanceID = 3065 }, never).instanceID)
        assert.is_nil(M.Status({ inInstance = true, instanceID = secret }, isSecret).instanceID)
    end)

    it("numbers cells row by row and rejects cells outside the grid", function()
        local M = load()
        assert.equal(1, M.CellIndex(1, 1))
        assert.equal(M.SKETCH.COLS + 2, M.CellIndex(2, 2))
        assert.is_nil(M.CellIndex(0, 1))
        assert.is_nil(M.CellIndex(M.SKETCH.COLS + 1, 1))
        assert.is_nil(M.CellIndex(1, M.SKETCH.ROWS + 1))
    end)

    it("paints, marks and erases; floor never overwrites a mark; reports changes only", function()
        local M = load()
        local sketch = {}
        assert.is_true(M.ApplyTool(sketch, 5, "floor"))
        assert.is_false(M.ApplyTool(sketch, 5, "floor"))
        assert.is_true(M.ApplyTool(sketch, 5, "boss"))
        assert.is_false(M.ApplyTool(sketch, 5, "floor"))
        assert.equal("boss", sketch[5])
        assert.is_true(M.ApplyTool(sketch, 5, "erase"))
        assert.is_nil(sketch[5])
        assert.is_false(M.ApplyTool(sketch, 5, "erase"))
        assert.is_false(M.ApplyTool(sketch, 6, "unknown"))
        assert.is_false(M.ApplyTool(sketch, nil, "floor"))
    end)

    it("keeps valid saved sketches and drops broken cells; Restore Defaults keeps the sketches", function()
        local M = load()
        local db = M.Migrate({ sketches = { ["id:1"] = { [1] = "floor", [2] = "boss", [3] = "lava", [0] = "floor",
            [99999] = "floor", [1.5] = "floor", x = "floor" }, ["id:2"] = "junk", [7] = {} } })
        assert.same({ ["id:1"] = { [1] = "floor", [2] = "boss" } }, db.sketches)
        M.RestoreDefaults(db)
        assert.same({ ["id:1"] = { [1] = "floor", [2] = "boss" } }, db.sketches)
        assert.same({}, M.Migrate({ sketches = "junk" }).sketches)
        assert.is_true(M.Migrate({}).showMap)
    end)
end)

describe("Map arrows", function()
    it("a click sets an arrow up, each further click turns it 45° clockwise, after 8 it points up again", function()
        local M = load()
        local sketch = {}
        assert.is_true(M.ApplyTool(sketch, 3, "arrow"))
        assert.equal("arrow0", sketch[3])
        for step = 1, 7 do
            M.ApplyTool(sketch, 3, "arrow")
            assert.equal("arrow" .. step, sketch[3])
        end
        M.ApplyTool(sketch, 3, "arrow")
        assert.equal("arrow0", sketch[3])
    end)

    it("an arrow is a mark: floor keeps it, erase removes it, a boss replaces it; saved arrows survive cleaning", function()
        local M = load()
        local sketch = { [4] = "arrow2" }
        assert.is_false(M.ApplyTool(sketch, 4, "floor"))
        assert.equal("arrow2", sketch[4])
        assert.is_true(M.ApplyTool(sketch, 4, "boss"))
        assert.equal("boss", sketch[4])
        assert.equal(2, M.ArrowDirection("arrow2"))
        assert.is_nil(M.ArrowDirection("arrow8"))
        assert.is_nil(M.ArrowDirection("boss"))
        local db = M.Migrate({ sketches = { ["id:1"] = { [1] = "arrow7", [2] = "arrow9", [3] = "arrowX" } } })
        assert.same({ ["id:1"] = { [1] = "arrow7" } }, db.sketches)
    end)
end)
